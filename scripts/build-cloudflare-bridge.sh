#!/usr/bin/env bash
# Bundles supabase/cloudflare-sandbox-bridge into a TS string module that
# cloudflare-adapter.ts uploads when it provisions a BYOS user's bridge.
# Re-run after changing the bridge or bumping @cloudflare/sandbox.
set -euo pipefail
cd "$(dirname "$0")/../supabase/cloudflare-sandbox-bridge"
npm install --no-audit --no-fund >/dev/null
out=$(mktemp)
npx esbuild src/index.ts --bundle --format=esm --platform=neutral --target=es2022 \
  --external:cloudflare:* --external:node:* --main-fields=module,main \
  --conditions=workerd,worker,browser --minify --outfile="$out" --log-level=warning
{
  echo "// Generated by scripts/build-cloudflare-bridge.sh from supabase/cloudflare-sandbox-bridge. Do not edit."
  echo "// @cloudflare/sandbox $(node -p 'require("./node_modules/@cloudflare/sandbox/package.json").version')"
  printf 'export const BRIDGE_SCRIPT: string = %s;\n' "$(node -e 'process.stdout.write(JSON.stringify(require("fs").readFileSync(process.argv[1],"utf8")))' "$out")"
} > ../functions/_shared/remote/cloudflare-bridge.generated.ts
rm -f "$out"
